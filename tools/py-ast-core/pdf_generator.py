def _infer_subsystems(symbols: list[dict]) -> list[str]:
    """Heuristic subsystem inference from symbol names and paths."""
    _MAP = {
        "Backend":   {"api", "route", "server", "handler", "controller", "middleware"},
        "Desktop":   {"window", "dialog", "widget", "gui", "app", "frame"},
        "Storage":   {"db", "database", "repo", "repository", "model", "schema", "orm", "query"},
        "Inference": {"model", "predict", "train", "infer", "embedding", "tensor", "neural"},
        "CLI":       {"cli", "args", "argv", "argparse", "click", "command"},
        "Testing":   {"test", "spec", "mock", "fixture", "assert"},
        "Utilities": {"util", "helper", "common", "shared", "base"},
    }
    found: set[str] = set()
    name_pool = " ".join(
        s.get("name", "").lower() + " " + s.get("file_path", "").lower()
        for s in symbols
    )
    for subsystem, keywords in _MAP.items():
        if any(kw in name_pool for kw in keywords):
            found.add(subsystem)
    return sorted(found)


def _guess_lang_from_path(fp: str) -> str:
    _EXT = {".py": "Python", ".go": "Go", ".ts": "TypeScript",
            ".tsx": "TypeScript", ".js": "JavaScript", ".jsx": "JavaScript"}
    ext = os.path.splitext(fp)[1].lower()
    return _EXT.get(ext, "-")


