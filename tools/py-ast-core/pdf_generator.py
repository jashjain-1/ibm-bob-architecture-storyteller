def _build_topology_image(
    edges: list[dict],
    entry_points: list[dict] | None = None,
    max_nodes: int = 40
) -> io.BytesIO | None:
    """
    Render a high-resolution, color-coded dependency & call graph as a PNG
    in an in-memory buffer for publication-grade PDF dossiers.
    """
    if not _MPL_OK or not edges:
        return None

    # Build adjacency limited to `calls` and `imports` edges
    adj: dict[str, set[str]] = defaultdict(set)
    for e in edges:
        if e.get("type") in ("calls", "imports"):
            src = e["from"].split("::")[-1]  # short name
            dst = e["to"].split("::")[-1]
            if src != dst:
                adj[src].add(dst)

    if not adj:
        return None

    # Identify entry point short names
    ep_names = set()
    if entry_points:
        for ep in entry_points:
            sym_id = ep.get("symbol_id", "")
            ep_names.add(sym_id.split("::")[-1])

    # Limit to top nodes by degree
    degree = {n: len(v) for n, v in adj.items()}
    top_nodes = sorted(degree, key=degree.get, reverse=True)[:max_nodes]  # type: ignore[arg-type]
    node_set = set(top_nodes)

    nodes = list(node_set)
    n = len(nodes)

    # Circular layout
    angles = [2 * math.pi * i / n for i in range(n)]
    pos = {nd: (math.cos(a), math.sin(a)) for nd, a in zip(nodes, angles)}

    fig, ax = plt.subplots(figsize=(8.5, 8.5), facecolor="#0F172A")
    ax.set_facecolor("#0F172A")
    ax.axis("off")

    # Draw edges with smooth alpha arrows
    for src, targets in adj.items():
        if src not in pos:
            continue
        x1, y1 = pos[src]
        for tgt in targets:
            if tgt not in pos:
                continue
            x2, y2 = pos[tgt]
            ax.annotate(
                "",
                xy=(x2, y2),
                xytext=(x1, y1),
                arrowprops=dict(
                    arrowstyle="-|>",
                    color="#475569",
                    lw=0.75,
                    alpha=0.6,
                    mutation_scale=9,
                ),
            )

    # Draw color-coded nodes
    for nd, (x, y) in pos.items():
        deg = degree.get(nd, 0)
        radius = 0.045 + 0.012 * min(deg, 8)

        if nd in ep_names:
            node_color = "#3B82F6"   # Electric Cobalt (Entry point)
            border_color = "#93C5FD"
        elif deg >= 4:
            node_color = "#8B5CF6"   # Deep Purple (Core Hub)
            border_color = "#C4B5FD"
        else:
            node_color = "#10B981"   # Emerald (Decoupled Leaf)
            border_color = "#6EE7B7"

        circle = plt.Circle(
            (x, y),
            radius,
            color=node_color,
            ec=border_color,
            lw=1.4,
            zorder=3,
            alpha=0.95
        )
        ax.add_patch(circle)

        label = nd if len(nd) <= 14 else nd[:12] + ".."
        ax.text(
            x,
            y - radius - 0.042,
            label,
            fontsize=5.5,
            color="#F1F5F9",
            ha="center",
            va="top",
            zorder=4,
            weight="bold"
        )

    # Legend inside the topology canvas
    ax.text(-1.30, 1.28, "IBM Bob 2.0 Architectural Interaction Topology",
            fontsize=9.5, color="#F8FAFC", weight="bold")
    ax.text(-1.30, 1.18, "Blue: Entry Point   |   Purple: Core Hub   |   Emerald: Safe Leaf   |   --> Call Graph Flow",
            fontsize=7, color="#94A3B8")

    ax.set_xlim(-1.35, 1.35)
    ax.set_ylim(-1.35, 1.35)
    ax.set_aspect("equal")
    fig.tight_layout(pad=0.1)

    buf = io.BytesIO()
    fig.savefig(
        buf,
        format="png",
        dpi=240,
        bbox_inches="tight",
        facecolor=fig.get_facecolor()
    )
    plt.close(fig)
    buf.seek(0)
    return buf


