def _analyse_coupling(symbols: list[dict], edges: list[dict]) -> dict:
    """
    Partition symbols into Cluster A (leaves), B (cycles), C (dynamic).
    Returns dict with keys 'leaves', 'cycles', 'dynamic'.
    """
    # Build call graph
    call_graph: dict[str, set[str]] = defaultdict(set)
    for e in edges:
        if e.get("type") == "calls":
            call_graph[e["from"]].add(e["to"])

    all_sym_ids = {s["id"] for s in symbols}

    # Detect cycles via iterative DFS
    visited: set[str] = set()
    in_stack: set[str] = set()
    cycles: list[set[str]] = []

    def dfs(node: str, stack: list[str]) -> None:
        visited.add(node)
        in_stack.add(node)
        stack.append(node)
        for nb in call_graph.get(node, set()):
            if nb not in all_sym_ids:
                continue
            if nb not in visited:
                dfs(nb, stack)
            elif nb in in_stack:
                # Found a cycle - collect it
                idx = stack.index(nb)
                cycles.append(set(stack[idx:]))
        stack.pop()
        in_stack.discard(node)

    for sym_id in all_sym_ids:
        if sym_id not in visited:
            dfs(sym_id, [])

    cycle_members: set[str] = set().union(*cycles) if cycles else set()

    # Dynamic patterns (eval / exec / __import__ / getattr in calls)
    _DYNAMIC_PATTERNS = {"eval", "exec", "__import__", "getattr", "setattr",
                         "importlib.import_module", "vars", "locals", "globals"}

    dynamic_ids: set[str] = set()
    for s in symbols:
        if any(c in _DYNAMIC_PATTERNS for c in s.get("calls", [])):
            dynamic_ids.add(s["id"])

    leaves = [
        s for s in symbols
        if s["id"] not in cycle_members
        and s["id"] not in dynamic_ids
        and not call_graph.get(s["id"])
    ]
    cycle_syms = [s for s in symbols if s["id"] in cycle_members]
    dynamic_syms = [s for s in symbols if s["id"] in dynamic_ids]

    # Coupling score E/V for cycles
    for sym in cycle_syms:
        out_edges = len(call_graph.get(sym["id"], set()))
        sym["_coupling_score"] = round(out_edges / max(1, len(cycle_syms)), 3)

    return {"leaves": leaves, "cycles": cycle_syms, "dynamic": dynamic_syms, "cycle_groups": cycles}


def _detect_dynamic_patterns(symbols: list[dict]) -> list[dict]:
    """
    Return a list of warning records for dynamic invocations.
    """
    _SEVERITY_MAP = {
        "eval": ("HIGH", "Arbitrary code execution - inject risk"),
        "exec": ("HIGH", "Arbitrary code execution - inject risk"),
        "__import__": ("HIGH", "Dynamic module loading bypasses static analysis"),
        "getattr": ("MED", "Dynamic attribute access hides call graph"),
        "setattr": ("MED", "Dynamic attribute mutation - refactor fragility"),
        "importlib.import_module": ("HIGH", "Runtime module loading - analyse carefully"),
        "vars": ("LOW", "Namespace introspection"),
        "locals": ("LOW", "Frame-local namespace access"),
        "globals": ("LOW", "Global namespace mutation risk"),
    }
    warnings = []
    for sym in symbols:
        for call in sym.get("calls", []):
            if call in _SEVERITY_MAP:
                sev, note = _SEVERITY_MAP[call]
                warnings.append({
                    "severity": sev,
                    "file_line": f"{sym['file_path']}:{sym['line_start']}",
                    "pattern": call,
                    "symbol": sym["name"],
                    "impact": note,
                })
    return warnings


