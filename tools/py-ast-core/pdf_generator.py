def build_pdf(ast_result: dict, project_name: str, output_path: str) -> str:
    """
    Build the full architecture dossier PDF.

    Parameters
    ----------
    ast_result:
        Output dict from ``extract_repo_ast_impl``.
    project_name:
        Human-readable project name used in headers and the cover page.
    output_path:
        Destination ``.pdf`` file path.

    Returns
    -------
    str
        Absolute path to the written PDF file.
    """
    if not _REPORTLAB_OK:
        raise ImportError(
            f"reportlab is required to generate PDFs. Install it with: "
            f"pip install 'reportlab>=4.0.0'. Original error: {_rl_err_msg}"
        )

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    styles = _build_styles()
    repo_path = ast_result.get("repo_path") or ast_result.get("meta", {}).get("repo_path") or os.getcwd()

    canvas_factory = _make_canvas_factory(project_name)

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        leftMargin=MARGIN_LEFT,
        rightMargin=MARGIN_RIGHT,
        topMargin=MARGIN_TOP + 0.6 * cm,   # extra top for running header
        bottomMargin=MARGIN_BOTTOM + 0.6 * cm,
        title=f"{project_name} - Architecture Dossier",
        author="IBM Bob 2.0 Polyglot Engine",
        subject="Polyglot AST Architecture Report",
        creator="IBM Bob 2.0",
    )

    story: list = []
    story += _section_cover(ast_result, project_name, repo_path, styles)
    story += _section_architecture_overview(ast_result, styles)
    story += _section_coupling(ast_result, styles)
    story += _section_dynamic_warnings(ast_result, styles)
    story += _section_playbook(ast_result, styles)

    doc.build(story, canvasmaker=canvas_factory)
    return os.path.abspath(output_path)
