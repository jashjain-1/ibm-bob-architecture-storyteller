def _make_canvas_factory(project_title: str):
    """
    Return a canvas *class* (not instance) that ReportLab's DocTemplate can
    use as a canvasmaker for the two-pass "Page X of Y" stamp.
    """

    class _PageCanvas(rl_canvas.Canvas):
        def __init__(self, filename, **kw):
            super().__init__(filename, **kw)
            self._title = project_title
            self._pages: list[dict] = []

        def showPage(self):  # noqa: N802
            self._pages.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            page_count = len(self._pages)
            for page_no, state in enumerate(self._pages, start=1):
                self.__dict__.update(state)
                if page_no > 1:
                    _draw_running_header(self, self._title)
                    _draw_running_footer(self, page_no, page_count)
                super().showPage()
            super().save()

    return _PageCanvas


def _draw_running_header(c: Any, title: str) -> None:
    c.saveState()
    y = PAGE_H - 1.4 * cm
    c.setFont("Helvetica-Bold", 8)
    c.setFillColor(C_HEADER_SLATE)
    c.drawString(MARGIN_LEFT, y, title)
    c.drawRightString(PAGE_W - MARGIN_RIGHT, y, "CONFIDENTIAL - ARCHITECTURE DOSSIER")
    c.setStrokeColor(C_BORDER_GRAY)
    c.setLineWidth(0.5)
    c.line(MARGIN_LEFT, y - 3, PAGE_W - MARGIN_RIGHT, y - 3)
    c.restoreState()


def _draw_running_footer(c: Any, page_no: int, total: int) -> None:
    c.saveState()
    y = 1.1 * cm
    c.setFont("Helvetica", 7.5)
    c.setFillColor(C_TEXT_MUTED)
    c.drawString(MARGIN_LEFT, y, "Generated by IBM Bob 2.0 Polyglot Engine")
    c.drawRightString(PAGE_W - MARGIN_RIGHT, y, f"Page {page_no} of {total}")
    c.setStrokeColor(C_BORDER_GRAY)
    c.setLineWidth(0.5)
    c.line(MARGIN_LEFT, y + 9, PAGE_W - MARGIN_RIGHT, y + 9)
    c.restoreState()


