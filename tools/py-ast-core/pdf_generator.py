class _StatCard(Flowable):
    """An executive KPI card with top accent bar, crisp metric, and subtitle."""

    W = 3.8 * cm
    H = 2.4 * cm

    def __init__(self, value: str, label: str, accent: Any = C_ACCENT_NAVY, sublabel: str = ""):
        super().__init__()
        self.value = value
        self.label = label
        self.accent = accent
        self.sublabel = sublabel
        self.width = self.W
        self.height = self.H

    def draw(self):
        c = self.canv
        c.saveState()
        # Card background
        c.setFillColor(colors.HexColor("#F8FAFC"))
        c.setStrokeColor(C_BORDER_GRAY)
        c.setLineWidth(0.75)
        c.roundRect(0, 0, self.W, self.H, 4, fill=1, stroke=1)

        # Accent top border
        c.setFillColor(self.accent)
        c.roundRect(0, self.H - 3.5, self.W, 3.5, 2, fill=1, stroke=0)

        # Metric Value
        c.setFont("Helvetica-Bold", 15)
        c.setFillColor(C_HEADER_SLATE)
        c.drawCentredString(self.W / 2, self.H / 2 + 2, self.value)

        # Label
        c.setFont("Helvetica-Bold", 7)
        c.setFillColor(C_TEXT_MUTED)
        c.drawCentredString(self.W / 2, self.H / 2 - 10, self.label.upper())

        if self.sublabel:
            c.setFont("Helvetica", 6)
            c.setFillColor(colors.HexColor("#94A3B8"))
            c.drawCentredString(self.W / 2, self.H / 2 - 18, self.sublabel)

        c.restoreState()


def _stat_cards_row(stats: list[tuple[str, str, Any, str]]) -> Table:
    """Arrange stat cards in a single-row table with individual accent colors."""
    cards = [_StatCard(val, lbl, acc, sub) for lbl, val, acc, sub in stats]
    data = [cards]
    col_w = [_StatCard.W + 0.3 * cm] * len(cards)
    t = Table(data, colWidths=col_w)
    t.setStyle(TableStyle([
        ("ALIGN",   (0, 0), (-1, -1), "CENTER"),
        ("VALIGN",  (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING",    (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    return t


